-- Supabase / PostgreSQL schema for the Grade Appeal demo.
-- Run once in Supabase Dashboard > SQL Editor. Safe to re-run.
-- Public browser code must use only the publishable key; RLS protects all rows.

create table if not exists public.departments (
  department_id bigint generated by default as identity primary key,
  department_name text not null unique,
  faculty_name text not null
);
create table if not exists public.users (
  user_id bigint generated by default as identity primary key,
  auth_user_id uuid unique references auth.users(id) on delete set null,
  username text not null unique,
  password_hash text,
  role text not null check (role in ('student','teacher','staff')),
  email text not null unique
);
create table if not exists public.teachers (
  teacher_id bigint generated by default as identity primary key,
  first_name text not null,
  last_name text not null,
  department_id bigint not null references public.departments,
  user_id bigint not null unique references public.users
);
create table if not exists public.students (
  student_id bigint generated by default as identity primary key,
  first_name text not null,
  last_name text not null,
  study_year smallint not null check (study_year between 1 and 8),
  department_id bigint not null references public.departments,
  user_id bigint not null unique references public.users
);
create table if not exists public.courses (
  course_id bigint generated by default as identity primary key,
  course_code text not null unique,
  course_name text not null,
  course_credit smallint not null check (course_credit > 0)
);
create table if not exists public.course_status (
  course_status_id bigint generated by default as identity primary key,
  status_name text not null unique,
  description text
);
create table if not exists public.course_offerings (
  offering_id bigint generated by default as identity primary key,
  course_id bigint not null references public.courses,
  teacher_id bigint not null references public.teachers,
  semester smallint not null check (semester in (1,2,3)),
  academic_year smallint not null,
  course_status_id bigint not null references public.course_status,
  unique(course_id,teacher_id,semester,academic_year)
);
create table if not exists public.enrollments (
  enrollment_id bigint generated by default as identity primary key,
  offering_id bigint not null references public.course_offerings,
  student_id bigint not null references public.students,
  grade text check (grade in ('A','B+','B','C+','C','D+','D','F')),
  unique(offering_id,student_id)
);
create table if not exists public.grade_appeals (
  appeals_id bigint generated by default as identity primary key,
  enrollment_id bigint not null references public.enrollments,
  grade_at_request text not null check (grade_at_request in ('A','B+','B','C+','C','D+','D','F')),
  reason text not null check (length(reason) >= 10),
  status text not null default 'pending' check (status in ('pending','reviewing','approved','rejected','cancelled'))
);
create unique index if not exists uq_active_appeal on public.grade_appeals(enrollment_id) where status <> 'cancelled';
create table if not exists public.appeal_reviews (
  review_id bigint generated by default as identity primary key,
  reviewer_id bigint not null references public.users,
  appeal_id bigint not null unique references public.grade_appeals(appeals_id),
  decision text not null check (decision in ('approved','rejected')),
  new_grade text not null check (new_grade in ('A','B+','B','C+','C','D+','D','F'))
);
create table if not exists public.appeal_status_history (
  history_id bigint generated by default as identity primary key,
  appeal_id bigint not null references public.grade_appeals(appeals_id),
  changed_by bigint not null references public.users,
  old_status text check (old_status in ('pending','reviewing','approved','rejected','cancelled')),
  new_status text not null check (new_status in ('pending','reviewing','approved','rejected','cancelled'))
);
create table if not exists public.appeal_attachments (
  attachment_id bigint generated by default as identity primary key,
  appeal_id bigint not null references public.grade_appeals(appeals_id),
  file_name text not null,
  file_type text not null,
  storage_path text
);
alter table public.appeal_attachments add column if not exists storage_path text;
create table if not exists public.grade_history (
  grade_history_id bigint generated by default as identity primary key,
  appeal_id bigint not null references public.grade_appeals(appeals_id),
  enrollment_id bigint not null references public.enrollments,
  old_grade text not null,
  new_grade text not null,
  changed_by bigint not null references public.users,
  check(old_grade <> new_grade)
);
create table if not exists public.notifications (
  notification_id bigint generated by default as identity primary key,
  appeal_id bigint not null references public.grade_appeals(appeals_id),
  user_id bigint not null references public.users,
  massage text not null,
  is_read boolean not null default false
);

create or replace function public.app_user_id() returns bigint
language sql stable security definer set search_path = public, auth
as $$ select user_id from public.users where auth_user_id = auth.uid() limit 1 $$;
create or replace function public.app_role() returns text
language sql stable security definer set search_path = public, auth
as $$ select role from public.users where auth_user_id = auth.uid() limit 1 $$;
create or replace function public.is_staff() returns boolean
language sql stable security definer set search_path = public, auth
as $$ select coalesce(public.app_role() = 'staff', false) $$;
revoke all on function public.app_user_id() from public;
revoke all on function public.app_role() from public;
revoke all on function public.is_staff() from public;
grant execute on function public.app_user_id(), public.app_role(), public.is_staff() to authenticated;

-- Self registration creates a student profile only; elevated roles are assigned
-- by a trusted administrator in the dashboard, never by browser metadata.
create or replace function public.handle_new_auth_user() returns trigger
language plpgsql security definer set search_path = public, auth
as $$
declare new_user_id bigint;
begin
  select user_id into new_user_id from public.users where email=new.email and auth_user_id is null for update;
  if found then
    update public.users set auth_user_id=new.id where user_id=new_user_id;
  else
    insert into public.users(auth_user_id,username,role,email)
    values(new.id, left(coalesce(nullif(new.raw_user_meta_data->>'username',''),split_part(new.email,'@',1)),40)||'_'||left(new.id::text,8), 'student', new.email)
    returning user_id into new_user_id;
  end if;
  if (select role from public.users where user_id=new_user_id)='student' then
    insert into public.students(first_name,last_name,study_year,department_id,user_id)
    values(coalesce(nullif(new.raw_user_meta_data->>'first_name',''),'นักศึกษา'),
           coalesce(nullif(new.raw_user_meta_data->>'last_name',''),''),1,
           (select min(department_id) from public.departments),new_user_id)
    on conflict(user_id) do nothing;
  end if;
  return new;
end $$;
drop trigger if exists on_auth_user_created_grade_appeal on auth.users;
create trigger on_auth_user_created_grade_appeal after insert on auth.users
for each row execute procedure public.handle_new_auth_user();

create or replace function public.guard_appeal_insert() returns trigger
language plpgsql security definer set search_path = public, auth
as $$
declare current_grade text; status_id bigint; owner_user_id bigint;
begin
  select e.grade,o.course_status_id,s.user_id into current_grade,status_id,owner_user_id
  from public.enrollments e join public.course_offerings o using(offering_id)
  join public.students s using(student_id) where e.enrollment_id=new.enrollment_id;
  if owner_user_id is distinct from public.app_user_id() then raise exception 'ยื่นคำร้องได้เฉพาะวิชาของบัญชีตนเอง'; end if;
  if status_id <> 2 or current_grade is null or current_grade <> new.grade_at_request then raise exception 'รายวิชายังไม่ประกาศเกรด หรือเกรดไม่ตรงกับข้อมูลปัจจุบัน'; end if;
  new.status := 'pending';
  return new;
end $$;
drop trigger if exists guard_appeal_before_insert on public.grade_appeals;
create trigger guard_appeal_before_insert before insert on public.grade_appeals
for each row execute procedure public.guard_appeal_insert();

create or replace function public.log_appeal_change() returns trigger
language plpgsql security definer set search_path = public, auth
as $$
declare e record; course_code_value text;
begin
  select en.student_id,st.user_id as student_user_id,off.teacher_id,t.user_id as teacher_user_id,c.course_code
    into e from public.enrollments en join public.students st using(student_id)
    join public.course_offerings off using(offering_id) join public.teachers t using(teacher_id)
    join public.courses c using(course_id) where en.enrollment_id=new.enrollment_id;
  if tg_op='INSERT' then
    insert into public.appeal_status_history(appeal_id,changed_by,old_status,new_status)
      values(new.appeals_id,public.app_user_id(),null,'pending');
    insert into public.notifications(appeal_id,user_id,massage)
      select new.appeals_id,u.user_id,'มีคำร้องใหม่ #'||new.appeals_id||' วิชา '||e.course_code||' รอเจ้าหน้าที่ยืนยัน' from public.users u where u.role='staff';
    insert into public.notifications(appeal_id,user_id,massage)
      values(new.appeals_id,e.teacher_user_id,'มีคำร้องใหม่ #'||new.appeals_id||' วิชา '||e.course_code||' รอเจ้าหน้าที่ยืนยัน');
  elsif old.status is distinct from new.status then
    insert into public.appeal_status_history(appeal_id,changed_by,old_status,new_status)
      values(new.appeals_id,public.app_user_id(),old.status,new.status);
    insert into public.notifications(appeal_id,user_id,massage)
      values(new.appeals_id,e.student_user_id,'สถานะคำร้อง #'||new.appeals_id||' เปลี่ยนเป็น '||new.status);
    if new.status='reviewing' then
      insert into public.notifications(appeal_id,user_id,massage)
        values(new.appeals_id,e.teacher_user_id,'คำร้อง #'||new.appeals_id||' วิชา '||e.course_code||' รอพิจารณา');
    end if;
  end if;
  return new;
end $$;
drop trigger if exists log_appeal_change_after_write on public.grade_appeals;
create trigger log_appeal_change_after_write after insert or update of status on public.grade_appeals
for each row execute procedure public.log_appeal_change();

create or replace function public.review_appeal(p_appeal_id bigint,p_decision text,p_new_grade text) returns void
language plpgsql security invoker set search_path = public, auth
as $$
declare a public.grade_appeals%rowtype; e public.enrollments%rowtype; teacher_user bigint;
begin
  if public.app_role()<>'teacher' or p_decision not in ('approved','rejected') then raise exception 'ไม่มีสิทธิ์พิจารณาคำร้อง'; end if;
  select * into a from public.grade_appeals where appeals_id=p_appeal_id for update;
  if not found or a.status<>'reviewing' then raise exception 'คำร้องนี้ไม่ได้อยู่ระหว่างพิจารณา'; end if;
  select en.* into e from public.enrollments en where en.enrollment_id=a.enrollment_id for update;
  select t.user_id into teacher_user from public.course_offerings o join public.teachers t using(teacher_id) where o.offering_id=e.offering_id;
  if teacher_user<>public.app_user_id() then raise exception 'พิจารณาได้เฉพาะรายวิชาที่สอน'; end if;
  if p_decision='approved' and p_new_grade not in ('A','B+','B','C+','C','D+','D','F') then raise exception 'เกรดไม่ถูกต้อง'; end if;
  insert into public.appeal_reviews(reviewer_id,appeal_id,decision,new_grade)
    values(public.app_user_id(),a.appeals_id,p_decision,case when p_decision='approved' then p_new_grade else e.grade end);
  if p_decision='approved' and e.grade is distinct from p_new_grade then
    update public.enrollments set grade=p_new_grade where enrollment_id=e.enrollment_id;
    insert into public.grade_history(appeal_id,enrollment_id,old_grade,new_grade,changed_by)
      values(a.appeals_id,e.enrollment_id,e.grade,p_new_grade,public.app_user_id());
  end if;
  update public.grade_appeals set status=p_decision where appeals_id=a.appeals_id;
end $$;
revoke all on function public.review_appeal(bigint,text,text) from public;
grant execute on function public.review_appeal(bigint,text,text) to authenticated;

create or replace function public.submit_appeal(p_enrollment_id bigint,p_reason text,p_files jsonb default '[]'::jsonb) returns bigint
language plpgsql security invoker set search_path = public, auth
as $$
declare e public.enrollments%rowtype; new_appeal_id bigint;
begin
  if public.app_role()<>'student' then raise exception 'เฉพาะนักศึกษาที่ยื่นคำร้องได้'; end if;
  select en.* into e from public.enrollments en join public.students s using(student_id)
    where en.enrollment_id=p_enrollment_id and s.user_id=public.app_user_id();
  if not found then raise exception 'ไม่พบรายวิชาของบัญชีนี้'; end if;
  insert into public.grade_appeals(enrollment_id,grade_at_request,reason)
    values(e.enrollment_id,e.grade,p_reason) returning appeals_id into new_appeal_id;
  insert into public.appeal_attachments(appeal_id,file_name,file_type,storage_path)
    select new_appeal_id,f->>'file_name',f->>'file_type',f->>'storage_path' from jsonb_array_elements(coalesce(p_files,'[]'::jsonb)) f;
  return new_appeal_id;
end $$;
revoke all on function public.submit_appeal(bigint,text,jsonb) from public;
grant execute on function public.submit_appeal(bigint,text,jsonb) to authenticated;

