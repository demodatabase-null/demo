-- หน้าประกาศเกรด (กรองด้วย student_ID ที่ฝั่งเว็บ)
CREATE OR REPLACE VIEW v_grade_announcement AS
SELECT e.enrollment_ID,
       s.student_ID,
       s.First_Name || ' ' || s.Last_Name AS student_name,
       c.course_code, c.course_name, c.course_credit,
       o.semester, o.academic_year,
       o.teacher_ID,
       o.course_status_id, cs.status_name AS course_status,
       e.grade             AS current_grade,
       a.appeals_ID, a.grade_at_request, a.status AS appeal_status
  FROM enrollment e
  JOIN student s          ON s.student_ID       = e.student_ID
  JOIN course_offering o  ON o.offering_ID      = e.offering_ID
  JOIN course c           ON c.course_ID        = o.course_ID
  JOIN course_status cs   ON cs.course_status_id = o.course_status_id
  LEFT JOIN grade_appeals a ON a.enrollment_ID  = e.enrollment_ID
                           AND a.status <> 'cancelled';

-- รายงานสรุปคำร้องแยกตามรายวิชา
CREATE OR REPLACE VIEW v_appeal_summary AS
SELECT o.offering_ID, c.course_code, c.course_name, o.semester, o.academic_year,
       COUNT(*)                                          AS total,
       SUM(CASE WHEN a.status = 'pending'   THEN 1 ELSE 0 END) AS pending,
       SUM(CASE WHEN a.status = 'reviewing' THEN 1 ELSE 0 END) AS reviewing,
       SUM(CASE WHEN a.status = 'approved'  THEN 1 ELSE 0 END) AS approved,
       SUM(CASE WHEN a.status = 'rejected'  THEN 1 ELSE 0 END) AS rejected,
       SUM(CASE WHEN a.status = 'cancelled' THEN 1 ELSE 0 END) AS cancelled
  FROM grade_appeals a
  JOIN enrollment e      ON e.enrollment_ID = a.enrollment_ID
  JOIN course_offering o ON o.offering_ID   = e.offering_ID
  JOIN course c          ON c.course_ID     = o.course_ID
 GROUP BY o.offering_ID, c.course_code, c.course_name, o.semester, o.academic_year;

-- ประวัติการแก้ไขเกรด
CREATE OR REPLACE VIEW v_grade_changes AS
SELECT h.grade_history_ID, h.appeal_ID,
       s.student_ID, s.First_Name || ' ' || s.Last_Name AS student_name,
       c.course_code, h.old_grade, h.new_grade, h.changed_by
  FROM grade_history h
  JOIN enrollment e      ON e.enrollment_ID = h.enrollment_ID
  JOIN student s         ON s.student_ID    = e.student_ID
  JOIN course_offering o ON o.offering_ID   = e.offering_ID
  JOIN course c          ON c.course_ID     = o.course_ID;

-- เกรดเฉลี่ย (ถ่วงน้ำหนักด้วยหน่วยกิต เฉพาะวิชาที่มีเกรดแล้ว)
CREATE OR REPLACE VIEW v_student_gpa AS
SELECT s.student_ID,
       ROUND(SUM(CASE e.grade WHEN 'A' THEN 4 WHEN 'B+' THEN 3.5 WHEN 'B' THEN 3 WHEN 'C+' THEN 2.5
                              WHEN 'C' THEN 2 WHEN 'D+' THEN 1.5 WHEN 'D' THEN 1 WHEN 'F' THEN 0 END
                  * c.course_credit) / NULLIF(SUM(c.course_credit), 0), 2) AS gpa
  FROM enrollment e
  JOIN student s         ON s.student_ID  = e.student_ID
  JOIN course_offering o ON o.offering_ID = e.offering_ID
  JOIN course c          ON c.course_ID   = o.course_ID
 WHERE e.grade IS NOT NULL
 GROUP BY s.student_ID;

