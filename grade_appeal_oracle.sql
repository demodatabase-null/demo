CREATE OR REPLACE FUNCTION f_person_name(p_user_id IN NUMBER) RETURN VARCHAR2 IS
  v VARCHAR2(250 CHAR);
BEGIN
  BEGIN
    SELECT 'อ.' || First_Name || ' ' || Last_Name INTO v FROM teachers WHERE user_ID = p_user_id;
    RETURN v;
  EXCEPTION WHEN NO_DATA_FOUND THEN NULL;
  END;
  BEGIN
    SELECT First_Name || ' ' || Last_Name INTO v FROM student WHERE user_ID = p_user_id;
    RETURN v;
  EXCEPTION WHEN NO_DATA_FOUND THEN NULL;
  END;
  RETURN 'เจ้าหน้าที่ทะเบียน';
END;
