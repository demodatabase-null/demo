-- =====================================================================
--  1) ตาราง (14 ตารางตามแผนภาพ ER)  PK / FK / constraints
-- =====================================================================

CREATE TABLE department (
  department_ID   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  department_name VARCHAR2(100 CHAR) NOT NULL,
  faculty_name    VARCHAR2(100 CHAR) NOT NULL,
  CONSTRAINT uq_department_name UNIQUE (department_name)
);

-- ตาราง User ใน ER (role: student / teacher / staff)
CREATE TABLE users (
  user_ID       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  username      VARCHAR2(50 CHAR)  NOT NULL,
  password_hash VARCHAR2(255 CHAR) NOT NULL,
  role          VARCHAR2(10 CHAR)  NOT NULL,
  email         VARCHAR2(100 CHAR) NOT NULL,
  CONSTRAINT uq_users_username UNIQUE (username),
  CONSTRAINT uq_users_email    UNIQUE (email),
  CONSTRAINT ck_users_role     CHECK (role IN ('student','teacher','staff'))
);

CREATE TABLE teachers (
  teacher_ID    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  First_Name    VARCHAR2(100 CHAR) NOT NULL,
  Last_Name     VARCHAR2(100 CHAR) NOT NULL,
  department_ID NUMBER NOT NULL,
  user_ID       NUMBER NOT NULL,
  CONSTRAINT uq_teachers_user UNIQUE (user_ID),                       -- User 1 : 1 Teachers
  CONSTRAINT fk_teachers_dept FOREIGN KEY (department_ID) REFERENCES department(department_ID),
  CONSTRAINT fk_teachers_user FOREIGN KEY (user_ID)       REFERENCES users(user_ID)
);

CREATE TABLE student (
  student_ID    NUMBER(10) PRIMARY KEY,
  First_Name    VARCHAR2(100 CHAR) NOT NULL,
  Last_Name     VARCHAR2(100 CHAR) NOT NULL,
  study_year    NUMBER(1) NOT NULL,
  department_ID NUMBER NOT NULL,
  user_ID       NUMBER NOT NULL,
  CONSTRAINT ck_student_year  CHECK (study_year BETWEEN 1 AND 8),
  CONSTRAINT uq_student_user  UNIQUE (user_ID),                       -- User 1 : 1 student
  CONSTRAINT fk_student_dept  FOREIGN KEY (department_ID) REFERENCES department(department_ID),
  CONSTRAINT fk_student_user  FOREIGN KEY (user_ID)       REFERENCES users(user_ID)
);

CREATE TABLE course (
  course_ID     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  course_code   VARCHAR2(20 CHAR)  NOT NULL,
  course_name   VARCHAR2(200 CHAR) NOT NULL,
  course_credit NUMBER(2) NOT NULL,
  CONSTRAINT uq_course_code   UNIQUE (course_code),
  CONSTRAINT ck_course_credit CHECK (course_credit > 0)
);

-- 1 = กำลังเรียน, 2 = ประกาศเกรดแล้ว (ยื่นคำร้องได้), 3 = ปิดรายวิชา
CREATE TABLE course_status (
  course_status_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  status_name      VARCHAR2(50 CHAR)  NOT NULL,
  description      VARCHAR2(255 CHAR),
  CONSTRAINT uq_course_status_name UNIQUE (status_name)
);

CREATE TABLE course_offering (
  offering_ID      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  course_ID        NUMBER NOT NULL,
  teacher_ID       NUMBER NOT NULL,
  semester         NUMBER(1) NOT NULL,
  academic_year    NUMBER(4) NOT NULL,
  course_status_id NUMBER NOT NULL,
  CONSTRAINT ck_offering_semester CHECK (semester IN (1,2,3)),
  CONSTRAINT uq_offering UNIQUE (course_ID, teacher_ID, semester, academic_year),
  CONSTRAINT fk_offering_course  FOREIGN KEY (course_ID)        REFERENCES course(course_ID),
  CONSTRAINT fk_offering_teacher FOREIGN KEY (teacher_ID)       REFERENCES teachers(teacher_ID),
  CONSTRAINT fk_offering_status  FOREIGN KEY (course_status_id) REFERENCES course_status(course_status_id)
);

CREATE TABLE enrollment (
  enrollment_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  offering_ID   NUMBER NOT NULL,
  student_ID    NUMBER(10) NOT NULL,
  grade         VARCHAR2(2 CHAR),                                      -- NULL = ยังไม่ประกาศเกรด
  CONSTRAINT ck_enrollment_grade CHECK (grade IN ('A','B+','B','C+','C','D+','D','F')),
  CONSTRAINT uq_enrollment UNIQUE (offering_ID, student_ID),
  CONSTRAINT fk_enrollment_offering FOREIGN KEY (offering_ID) REFERENCES course_offering(offering_ID),
  CONSTRAINT fk_enrollment_student  FOREIGN KEY (student_ID)  REFERENCES student(student_ID)
);

-- status: pending(รอเจ้าหน้าที่) / reviewing(รออาจารย์) / approved / rejected / cancelled
CREATE TABLE grade_appeals (
  appeals_ID       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  enrollment_ID    NUMBER NOT NULL,
  grade_at_request VARCHAR2(2 CHAR) NOT NULL,                          -- เกรด ณ วันยื่น (snapshot)
  reason           VARCHAR2(1000 CHAR) NOT NULL,
  status           VARCHAR2(10 CHAR) DEFAULT 'pending' NOT NULL,
  CONSTRAINT ck_appeal_status CHECK (status IN ('pending','reviewing','approved','rejected','cancelled')),
  CONSTRAINT ck_appeal_grade  CHECK (grade_at_request IN ('A','B+','B','C+','C','D+','D','F')),
  CONSTRAINT ck_appeal_reason CHECK (LENGTH(reason) >= 10),
  CONSTRAINT fk_appeal_enrollment FOREIGN KEY (enrollment_ID) REFERENCES enrollment(enrollment_ID)
);

-- กฎ: ห้ามมีคำร้องของวิชา (enrollment) เดิมที่ยังไม่ยกเลิกซ้ำ  (ยื่นใหม่ได้หลังยกเลิก)
CREATE UNIQUE INDEX uq_active_appeal
  ON grade_appeals (CASE WHEN status <> 'cancelled' THEN enrollment_ID END);

-- 1 คำร้องมีผลพิจารณา 1 ครั้ง (grade_appeals 1 : 1 appeal_reviews)
CREATE TABLE appeal_reviews (
  review_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  reviewer_id NUMBER NOT NULL,
  appeal_id   NUMBER NOT NULL,
  decision    VARCHAR2(10 CHAR) NOT NULL,
  new_grade   VARCHAR2(2 CHAR)  NOT NULL,
  CONSTRAINT uq_review_appeal  UNIQUE (appeal_id),
  CONSTRAINT ck_review_decision CHECK (decision IN ('approved','rejected')),
  CONSTRAINT ck_review_grade    CHECK (new_grade IN ('A','B+','B','C+','C','D+','D','F')),
  CONSTRAINT fk_review_reviewer FOREIGN KEY (reviewer_id) REFERENCES users(user_ID),
  CONSTRAINT fk_review_appeal   FOREIGN KEY (appeal_id)   REFERENCES grade_appeals(appeals_ID)
);

CREATE TABLE appeal_status_history (
  history_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  appeal_ID  NUMBER NOT NULL,
  changed_by NUMBER NOT NULL,
  old_status VARCHAR2(10 CHAR),                                        -- NULL ตอนยื่นคำร้องครั้งแรก
  new_status VARCHAR2(10 CHAR) NOT NULL,
  CONSTRAINT ck_hist_old CHECK (old_status IN ('pending','reviewing','approved','rejected','cancelled')),
  CONSTRAINT ck_hist_new CHECK (new_status IN ('pending','reviewing','approved','rejected','cancelled')),
  CONSTRAINT fk_hist_appeal FOREIGN KEY (appeal_ID)  REFERENCES grade_appeals(appeals_ID),
  CONSTRAINT fk_hist_user   FOREIGN KEY (changed_by) REFERENCES users(user_ID)
);

-- หมายเหตุ: ใน ER ฟิลด์ file_name ถูกติดป้าย FK แต่ไม่มีตารางที่ถูกอ้างอิง จึงสร้างเป็นคอลัมน์ธรรมดา
CREATE TABLE appeal_attachment (
  attachment_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  appeal_ID     NUMBER NOT NULL,
  file_name     VARCHAR2(255 CHAR) NOT NULL,
  file_type     VARCHAR2(20 CHAR)  NOT NULL,
  CONSTRAINT fk_attach_appeal FOREIGN KEY (appeal_ID) REFERENCES grade_appeals(appeals_ID)
);

CREATE TABLE grade_history (
  grade_history_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  appeal_ID        NUMBER NOT NULL,
  enrollment_ID    NUMBER NOT NULL,
  old_grade        VARCHAR2(2 CHAR) NOT NULL,
  new_grade        VARCHAR2(2 CHAR) NOT NULL,
  changed_by       NUMBER NOT NULL,
  CONSTRAINT ck_gh_diff CHECK (old_grade <> new_grade),
  CONSTRAINT fk_gh_appeal     FOREIGN KEY (appeal_ID)     REFERENCES grade_appeals(appeals_ID),
  CONSTRAINT fk_gh_enrollment FOREIGN KEY (enrollment_ID) REFERENCES enrollment(enrollment_ID),
  CONSTRAINT fk_gh_user       FOREIGN KEY (changed_by)    REFERENCES users(user_ID)
);

CREATE TABLE notification (
  notification_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  appeal_ID       NUMBER NOT NULL,
  user_id         NUMBER NOT NULL,
  massage         VARCHAR2(500 CHAR) NOT NULL,                         -- ตามชื่อฟิลด์ใน ER
  is_read         NUMBER(1) DEFAULT 0 NOT NULL,
  CONSTRAINT ck_notif_read CHECK (is_read IN (0,1)),
  CONSTRAINT fk_notif_appeal FOREIGN KEY (appeal_ID) REFERENCES grade_appeals(appeals_ID),
  CONSTRAINT fk_notif_user   FOREIGN KEY (user_id)   REFERENCES users(user_ID)
);

-- =====================================================================
--  2) Trigger: กฎทางธุรกิจที่ฐานข้อมูลต้องปฏิเสธ
-- =====================================================================

-- กฎ 2: ยื่นได้เฉพาะวิชาที่ประกาศเกรดแล้ว (course_status_id = 2) และต้องมีเกรด
CREATE OR REPLACE TRIGGER trg_appeal_published
BEFORE INSERT ON grade_appeals
FOR EACH ROW
DECLARE
  v_status NUMBER;
  v_grade  enrollment.grade%TYPE;
BEGIN
  SELECT o.course_status_id, e.grade
    INTO v_status, v_grade
    FROM enrollment e
    JOIN course_offering o ON o.offering_ID = e.offering_ID
   WHERE e.enrollment_ID = :NEW.enrollment_ID;

  IF v_status <> 2 THEN
    RAISE_APPLICATION_ERROR(-20001,
      'ยื่นคำร้องไม่ได้: รายวิชานี้ยังไม่ประกาศเกรด (course_status_id = ' || v_status || ')');
  END IF;
  IF v_grade IS NULL THEN
    RAISE_APPLICATION_ERROR(-20002, 'ยื่นคำร้องไม่ได้: ยังไม่มีเกรดให้ตรวจสอบ');
  END IF;
END;
/

-- กฎ 3: ยกเลิกไม่ได้เมื่ออาจารย์ตัดสินแล้ว / สถานะสุดท้ายห้ามเปลี่ยน
CREATE OR REPLACE TRIGGER trg_appeal_status_guard
BEFORE UPDATE OF status ON grade_appeals
FOR EACH ROW
BEGIN
  IF :OLD.status IN ('approved','rejected','cancelled') AND :NEW.status <> :OLD.status THEN
    IF :NEW.status = 'cancelled' THEN
      RAISE_APPLICATION_ERROR(-20003,
        'ยกเลิกไม่ได้: คำร้อง #' || :OLD.appeals_ID || ' มีผลพิจารณาแล้ว (status = ' || :OLD.status || ')');
    ELSE
      RAISE_APPLICATION_ERROR(-20004,
        'เปลี่ยนสถานะไม่ได้: คำร้อง #' || :OLD.appeals_ID || ' อยู่ในสถานะสุดท้ายแล้ว (' || :OLD.status || ')');
    END IF;
  END IF;
END;
/

