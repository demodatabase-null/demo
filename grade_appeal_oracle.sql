-- C) อาจารย์ยืนยันผลพิจารณา (reviewing -> approved / rejected)
--    อนุมัติ  : appeal_reviews, grade_history, enrollment.grade, grade_appeals, appeal_status_history, notification
--    ไม่อนุมัติ: appeal_reviews, grade_appeals, appeal_status_history, notification (เกรดคงเดิม)
CREATE OR REPLACE PROCEDURE sp_teacher_decide(
  p_appeal_id       IN NUMBER,
  p_teacher_user_id IN NUMBER,
  p_decision        IN VARCHAR2,      -- 'approved' | 'rejected'
  p_new_grade       IN VARCHAR2       -- ใช้เมื่อ approved (ถ้า rejected ส่ง NULL ได้)
) AS
  v_status        grade_appeals.status%TYPE;
  v_enrollment    NUMBER;
  v_old_grade     enrollment.grade%TYPE;
  v_student_user  NUMBER;
  v_owner_user    NUMBER;
  v_course_code   course.course_code%TYPE;
  v_new_grade     VARCHAR2(2 CHAR);
BEGIN
  IF p_decision NOT IN ('approved','rejected') THEN
    RAISE_APPLICATION_ERROR(-20030, 'decision ต้องเป็น approved หรือ rejected');
  END IF;

  SELECT a.status, a.enrollment_ID, e.grade, s.user_ID, t.user_ID, c.course_code
    INTO v_status, v_enrollment, v_old_grade, v_student_user, v_owner_user, v_course_code
    FROM grade_appeals a
    JOIN enrollment e      ON e.enrollment_ID = a.enrollment_ID
    JOIN student s         ON s.student_ID    = e.student_ID
    JOIN course_offering o ON o.offering_ID   = e.offering_ID
    JOIN teachers t        ON t.teacher_ID    = o.teacher_ID
    JOIN course c          ON c.course_ID     = o.course_ID
   WHERE a.appeals_ID = p_appeal_id
     FOR UPDATE OF a.status;

  IF v_owner_user <> p_teacher_user_id THEN
    RAISE_APPLICATION_ERROR(-20031, 'พิจารณาได้เฉพาะคำร้องของรายวิชาที่ตนสอน');
  END IF;
  IF v_status <> 'reviewing' THEN
    RAISE_APPLICATION_ERROR(-20032, 'พิจารณาไม่ได้: คำร้องอยู่ในสถานะ ' || v_status || ' (ต้องเป็น reviewing)');
  END IF;

  IF p_decision = 'approved' THEN
    IF p_new_grade IS NULL OR p_new_grade = v_old_grade THEN
      RAISE_APPLICATION_ERROR(-20033, 'ต้องระบุเกรดใหม่ที่ต่างจากเกรดเดิม (' || v_old_grade || ')');
    END IF;
    v_new_grade := p_new_grade;
  ELSE
    v_new_grade := v_old_grade;   -- ไม่อนุมัติ = คงเกรดเดิม
  END IF;

  INSERT INTO appeal_reviews (reviewer_id, appeal_id, decision, new_grade)
  VALUES (p_teacher_user_id, p_appeal_id, p_decision, v_new_grade);

  IF p_decision = 'approved' THEN
    INSERT INTO grade_history (appeal_ID, enrollment_ID, old_grade, new_grade, changed_by)
    VALUES (p_appeal_id, v_enrollment, v_old_grade, v_new_grade, p_teacher_user_id);
    UPDATE enrollment SET grade = v_new_grade WHERE enrollment_ID = v_enrollment;
  END IF;

  INSERT INTO appeal_status_history (appeal_ID, changed_by, old_status, new_status)
  VALUES (p_appeal_id, p_teacher_user_id, v_status, p_decision);
  UPDATE grade_appeals SET status = p_decision WHERE appeals_ID = p_appeal_id;

  INSERT INTO notification (appeal_ID, user_id, massage, is_read)
  VALUES (p_appeal_id, v_student_user,
          CASE WHEN p_decision = 'approved'
               THEN 'คำร้อง #' || p_appeal_id || ' (' || v_course_code || ') ได้รับการอนุมัติ เกรดเปลี่ยนจาก ' || v_old_grade || ' เป็น ' || v_new_grade
               ELSE 'คำร้อง #' || p_appeal_id || ' (' || v_course_code || ') ไม่ได้รับการอนุมัติ คงเกรดเดิม ' || v_old_grade
          END, 0);

  COMMIT;
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    ROLLBACK;
    RAISE_APPLICATION_ERROR(-20013, 'ไม่พบคำร้องนี้');
  WHEN OTHERS THEN
    ROLLBACK;
    RAISE;
END;
/

-- D) นักศึกษายกเลิกคำร้อง (pending / reviewing -> cancelled)
--    เปลี่ยน: grade_appeals, appeal_status_history, notification
--    ถ้าอาจารย์ตัดสินแล้ว trigger trg_appeal_status_guard จะปฏิเสธ
CREATE OR REPLACE PROCEDURE sp_cancel_appeal(
  p_appeal_id       IN NUMBER,
  p_student_user_id IN NUMBER
) AS
  v_status       grade_appeals.status%TYPE;
  v_owner        NUMBER;
  v_teacher_user NUMBER;
  v_course_code  course.course_code%TYPE;
  v_name         VARCHAR2(250 CHAR);
BEGIN
  SELECT a.status, s.user_ID, t.user_ID, c.course_code, s.First_Name || ' ' || s.Last_Name
    INTO v_status, v_owner, v_teacher_user, v_course_code, v_name
    FROM grade_appeals a
    JOIN enrollment e      ON e.enrollment_ID = a.enrollment_ID
    JOIN student s         ON s.student_ID    = e.student_ID
    JOIN course_offering o ON o.offering_ID   = e.offering_ID
    JOIN teachers t        ON t.teacher_ID    = o.teacher_ID
    JOIN course c          ON c.course_ID     = o.course_ID
   WHERE a.appeals_ID = p_appeal_id
     FOR UPDATE OF a.status;

  IF v_owner <> p_student_user_id THEN
    RAISE_APPLICATION_ERROR(-20040, 'ยกเลิกได้เฉพาะคำร้องของตัวเอง');
  END IF;

  UPDATE grade_appeals SET status = 'cancelled' WHERE appeals_ID = p_appeal_id;  -- trigger ตรวจกฎ

  INSERT INTO appeal_status_history (appeal_ID, changed_by, old_status, new_status)
  VALUES (p_appeal_id, p_student_user_id, v_status, 'cancelled');

  FOR u IN (SELECT user_ID FROM users WHERE role = 'staff') LOOP
    INSERT INTO notification (appeal_ID, user_id, massage, is_read)
    VALUES (p_appeal_id, u.user_ID,
            'นักศึกษา ' || v_name || ' ยกเลิกคำร้อง #' || p_appeal_id || ' วิชา ' || v_course_code, 0);
  END LOOP;
  INSERT INTO notification (appeal_ID, user_id, massage, is_read)
  VALUES (p_appeal_id, v_teacher_user,
          'นักศึกษา ' || v_name || ' ยกเลิกคำร้อง #' || p_appeal_id || ' วิชา ' || v_course_code || ' ไม่ต้องพิจารณาต่อ', 0);

  COMMIT;
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    ROLLBACK;
    RAISE_APPLICATION_ERROR(-20013, 'ไม่พบคำร้องนี้');
  WHEN OTHERS THEN
    ROLLBACK;
    RAISE;
END;
