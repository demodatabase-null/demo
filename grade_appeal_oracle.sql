-- ตั้งค่าตัวนับ identity ให้เริ่มต่อจากข้อมูลตัวอย่าง (ต้องใช้ Oracle 12.2 ขึ้นไป)
BEGIN
  FOR r IN (
    SELECT 'DEPARTMENT' t, 'DEPARTMENT_ID' c FROM dual UNION ALL
    SELECT 'USERS', 'USER_ID' FROM dual UNION ALL
    SELECT 'TEACHERS', 'TEACHER_ID' FROM dual UNION ALL
    SELECT 'COURSE', 'COURSE_ID' FROM dual UNION ALL
    SELECT 'COURSE_STATUS', 'COURSE_STATUS_ID' FROM dual UNION ALL
    SELECT 'COURSE_OFFERING', 'OFFERING_ID' FROM dual UNION ALL
    SELECT 'ENROLLMENT', 'ENROLLMENT_ID' FROM dual UNION ALL
    SELECT 'GRADE_APPEALS', 'APPEALS_ID' FROM dual UNION ALL
    SELECT 'APPEAL_REVIEWS', 'REVIEW_ID' FROM dual UNION ALL
    SELECT 'APPEAL_STATUS_HISTORY', 'HISTORY_ID' FROM dual UNION ALL
    SELECT 'APPEAL_ATTACHMENT', 'ATTACHMENT_ID' FROM dual UNION ALL
    SELECT 'GRADE_HISTORY', 'GRADE_HISTORY_ID' FROM dual UNION ALL
    SELECT 'NOTIFICATION', 'NOTIFICATION_ID' FROM dual
  ) LOOP
    EXECUTE IMMEDIATE 'ALTER TABLE ' || r.t || ' MODIFY (' || r.c ||
                      ' GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH LIMIT VALUE))';
  END LOOP;
END;
