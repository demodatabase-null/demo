-- B1) เจ้าหน้าที่ยืนยันคำร้อง (pending -> reviewing)
--     เปลี่ยน: grade_appeals, appeal_status_history, notification (นักศึกษา + อาจารย์)
CREATE OR REPLACE PROCEDURE sp_staff_confirm(
  p_appeal_id     IN NUMBER,
  p_staff_user_id IN NUMBER
) AS
  v_status       grade_appeals.status%TYPE;
  v_role         users.role%TYPE;
  v_student_user NUMBER;
  v_teacher_user NUMBER;
  v_course_code  course.course_code%TYPE;
  v_student_name VARCHAR2(250 CHAR);
BEGIN
  SELECT role INTO v_role FROM users WHERE user_ID = p_staff_user_id;
  IF v_role <> 'staff' THEN
    RAISE_APPLICATION_ERROR(-20020, 'เฉพาะเจ้าหน้าที่เท่านั้นที่ยืนยันคำร้องได้');
  END IF;

  SELECT a.status, s.user_ID, t.user_ID, c.course_code, s.First_Name || ' ' || s.Last_Name
    INTO v_status, v_student_user, v_teacher_user, v_course_code, v_student_name
    FROM grade_appeals a
    JOIN enrollment e      ON e.enrollment_ID = a.enrollment_ID
    JOIN student s         ON s.student_ID    = e.student_ID
    JOIN course_offering o ON o.offering_ID   = e.offering_ID
    JOIN teachers t        ON t.teacher_ID    = o.teacher_ID
    JOIN course c          ON c.course_ID     = o.course_ID
   WHERE a.appeals_ID = p_appeal_id
     FOR UPDATE OF a.status;

  IF v_status <> 'pending' THEN
    RAISE_APPLICATION_ERROR(-20021, 'คำร้องนี้ถูกเปลี่ยนสถานะแล้ว (status = ' || v_status || ')');
  END IF;

  INSERT INTO appeal_status_history (appeal_ID, changed_by, old_status, new_status)
  VALUES (p_appeal_id, p_staff_user_id, v_status, 'reviewing');

  UPDATE grade_appeals SET status = 'reviewing' WHERE appeals_ID = p_appeal_id;

  INSERT INTO notification (appeal_ID, user_id, massage, is_read)
  VALUES (p_appeal_id, v_student_user,
          'เจ้าหน้าที่ยืนยันคำร้อง #' || p_appeal_id || ' (' || v_course_code || ') แล้ว ส่งต่ออาจารย์ผู้สอน', 0);
  INSERT INTO notification (appeal_ID, user_id, massage, is_read)
  VALUES (p_appeal_id, v_teacher_user,
          'คำร้อง #' || p_appeal_id || ' จาก ' || v_student_name || ' วิชา ' || v_course_code ||
          ' ผ่านการยืนยันจากเจ้าหน้าที่ รอพิจารณา', 0);

  COMMIT;
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    ROLLBACK;
    RAISE_APPLICATION_ERROR(-20013, 'ไม่พบคำร้องหรือผู้ใช้นี้');
  WHEN OTHERS THEN
    ROLLBACK;
    RAISE;
END;
