-- A) นักศึกษายื่นคำร้อง
--    เปลี่ยน: grade_appeals, appeal_status_history, notification (เจ้าหน้าที่ทุกคน + อาจารย์ผู้สอน)
CREATE OR REPLACE PROCEDURE sp_submit_appeal(
  p_enrollment_id   IN  NUMBER,
  p_reason          IN  VARCHAR2,
  p_student_user_id IN  NUMBER,
  p_appeal_id       OUT NUMBER
) AS
  v_grade        enrollment.grade%TYPE;
  v_owner        NUMBER;
  v_teacher_user NUMBER;
  v_course_code  course.course_code%TYPE;
  v_student_name VARCHAR2(250 CHAR);
BEGIN
  SELECT e.grade, s.user_ID, t.user_ID, c.course_code, s.First_Name || ' ' || s.Last_Name
    INTO v_grade, v_owner, v_teacher_user, v_course_code, v_student_name
    FROM enrollment e
    JOIN student s         ON s.student_ID  = e.student_ID
    JOIN course_offering o ON o.offering_ID = e.offering_ID
    JOIN teachers t        ON t.teacher_ID  = o.teacher_ID
    JOIN course c          ON c.course_ID   = o.course_ID
   WHERE e.enrollment_ID = p_enrollment_id;

  IF v_owner <> p_student_user_id THEN
    RAISE_APPLICATION_ERROR(-20010, 'ยื่นคำร้องได้เฉพาะวิชาของตัวเอง');
  END IF;
  IF v_grade IS NULL THEN
    RAISE_APPLICATION_ERROR(-20002, 'ยื่นคำร้องไม่ได้: ยังไม่มีเกรดให้ตรวจสอบ');
  END IF;

  -- trigger trg_appeal_published ตรวจ course_status_id = 2, unique index uq_active_appeal กันยื่นซ้ำ
  INSERT INTO grade_appeals (enrollment_ID, grade_at_request, reason, status)
  VALUES (p_enrollment_id, v_grade, p_reason, 'pending')
  RETURNING appeals_ID INTO p_appeal_id;

  INSERT INTO appeal_status_history (appeal_ID, changed_by, old_status, new_status)
  VALUES (p_appeal_id, p_student_user_id, NULL, 'pending');

  FOR u IN (SELECT user_ID FROM users WHERE role = 'staff') LOOP
    INSERT INTO notification (appeal_ID, user_id, massage, is_read)
    VALUES (p_appeal_id, u.user_ID,
            'มีคำร้องใหม่ #' || p_appeal_id || ' จาก ' || v_student_name || ' วิชา ' || v_course_code || ' รอเจ้าหน้าที่ยืนยัน', 0);
  END LOOP;

  INSERT INTO notification (appeal_ID, user_id, massage, is_read)
  VALUES (p_appeal_id, v_teacher_user,
          'นักศึกษา ' || v_student_name || ' ยื่นคำร้อง #' || p_appeal_id || ' วิชา ' || v_course_code ||
          ' (รอเจ้าหน้าที่ยืนยันก่อนส่งให้พิจารณา)', 0);

  COMMIT;
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    ROLLBACK;
    RAISE_APPLICATION_ERROR(-20013, 'ไม่พบข้อมูลการลงทะเบียนนี้');
  WHEN DUP_VAL_ON_INDEX THEN
    ROLLBACK;
    RAISE_APPLICATION_ERROR(-20012, 'ยื่นคำร้องไม่ได้: วิชานี้มีคำร้องที่ยังไม่ยกเลิกอยู่แล้ว');
  WHEN OTHERS THEN
    ROLLBACK;
    RAISE;
END;
/

